#!/usr/bin/env node
/**
 * Creates (or resets) the store-owner login in Cloudflare D1.
 *
 * Plain SQL cannot create an admin because the password must be stored as a
 * PBKDF2 hash. This script computes that hash locally and writes an
 * `admin-seed.sql` file you then run against D1. It is an upsert, so it also
 * repairs an existing admin row (wrong hash) and signs out old sessions.
 *
 * Usage (PowerShell):
 *   $env:ADMIN_EMAIL = "you@example.com"
 *   $env:ADMIN_PASSWORD = "your-strong-password"
 *   node scripts/create-admin-sql.mjs
 *   npx wrangler d1 execute hijabi-by-anayah-db --remote --file=admin-seed.sql
 *   Remove-Item admin-seed.sql
 *
 * Usage (bash):
 *   ADMIN_EMAIL="you@example.com" ADMIN_PASSWORD="..." node scripts/create-admin-sql.mjs
 *
 * The hash format matches src/lib/auth.functions.ts:
 *   pbkdf2$<iterations>$<base64 salt>$<base64 PBKDF2-SHA256 hash>
 * Iterations are capped at 100,000 because Cloudflare Workers reject more.
 */
import { pbkdf2Sync, randomBytes, randomUUID } from "node:crypto";
import { writeFileSync } from "node:fs";

const ITERATIONS = 100_000;
const OUT_FILE = "admin-seed.sql";

const email = (process.env.ADMIN_EMAIL ?? process.argv[2] ?? "").trim().toLowerCase();
const password = process.env.ADMIN_PASSWORD ?? process.argv[3] ?? "";

if (!/^[^\s@']+@[^\s@']+\.[^\s@']+$/.test(email)) {
  console.error("Set ADMIN_EMAIL to a valid email address.");
  process.exit(1);
}
if (password.length < 8) {
  console.error("Set ADMIN_PASSWORD (at least 8 characters).");
  process.exit(1);
}

const salt = randomBytes(16);
const hash = pbkdf2Sync(password, salt, ITERATIONS, 32, "sha256");
const passwordHash = `pbkdf2$${ITERATIONS}$${salt.toString("base64")}$${hash.toString("base64")}`;

// email is validated above (no quotes); base64 hash/uuid contain no quotes.
const sql = `-- Generated by scripts/create-admin-sql.mjs. Contains a password HASH; do not commit.
INSERT INTO admin_users (id, email, password_hash, full_name, active)
VALUES ('${randomUUID()}', '${email}', '${passwordHash}', 'Anayah Admin', 1)
ON CONFLICT(email) DO UPDATE SET
  password_hash = excluded.password_hash,
  active = 1,
  updated_at = CURRENT_TIMESTAMP;

DELETE FROM admin_sessions
WHERE admin_id IN (SELECT id FROM admin_users WHERE email = '${email}' COLLATE NOCASE);
`;

writeFileSync(OUT_FILE, sql, { encoding: "utf8" });

console.log(`Wrote ${OUT_FILE} for ${email}.`);
console.log("Next:");
console.log("  npx wrangler d1 execute hijabi-by-anayah-db --remote --file=admin-seed.sql");
console.log("Then delete admin-seed.sql.");
